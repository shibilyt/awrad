#!/usr/bin/env python3
"""Generates AwradDomain's Umm al-Qura table from contracts/hijri-calendar/v1/umm-al-qura.json.

The app ships the table offline, so it's compiled in as Swift source; nothing reads contracts/ at
runtime. Run without arguments to rewrite the Swift file. With --check (scripts/validate), it
fails when the committed file differs from what the contract generates: the freshness check.
"""
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT.parent / "contracts" / "hijri-calendar" / "v1" / "umm-al-qura.json"
OUTPUT = ROOT / "AwradKit" / "Sources" / "AwradDomain" / "UmmAlQuraTable.swift"
EPOCH = date(1970, 1, 1).toordinal()


def ordinal(day: str) -> int:
    """Days since 1970-01-01, the encoding CalendarDay(ordinal:) reads."""
    return date.fromisoformat(day).toordinal() - EPOCH


def generate() -> str:
    table = json.loads(CONTRACT.read_text(encoding="utf-8"))
    first, last = table["first_year"], table["last_year"]
    years = [str(year) for year in range(first, last + 1)]
    if sorted(table["month_starts"]) != years:
        raise SystemExit(f"hijri table: month_starts must hold every year {first}–{last}")
    rows = []
    for year in years:
        starts = table["month_starts"][year]
        if len(starts) != 12:
            raise SystemExit(f"hijri table: {year} doesn't have 12 months")
        rows.append(f"        {', '.join(str(ordinal(s)) for s in starts)},  // {year}: {starts[0]}")
    end = table["end_exclusive"]
    lines = [
        "// Generated by scripts/generate-hijri-table.py from contracts/hijri-calendar/v1/umm-al-qura.json.",
        "// Don't edit: regenerate it. scripts/validate fails when it differs from the contract.",
        "",
        "/// The shared Umm al-Qura month table (root ADR-2026-10-26), compiled in so it works offline.",
        "enum UmmAlQuraTable {",
        f"    static let firstYear = {first}",
        f"    static let lastYear = {last}",
        "",
        "    /// The Gregorian start of every month, 1 Muharram of `firstYear` first, as days since",
        "    /// 1970-01-01 (`CalendarDay.ordinal`). Twelve per row, one row per Hijri year.",
        "    static let monthStarts: [Int] = [",
        *rows,
        "    ]",
        "",
        "    /// The day after the table's last month ends, as days since 1970-01-01.",
        f"    static let endExclusive = {ordinal(end)}  // {end}",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    generated = generate()
    if sys.argv[1:] == ["--check"]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            print(
                f"hijri table: {OUTPUT.relative_to(ROOT)} is stale or edited; "
                "run scripts/generate-hijri-table.py",
                file=sys.stderr,
            )
            return 1
        print("hijri table: matches contracts/hijri-calendar/v1/umm-al-qura.json")
        return 0
    if sys.argv[1:]:
        print("usage: generate-hijri-table.py [--check]", file=sys.stderr)
        return 2
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"hijri table: wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
