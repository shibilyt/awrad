#!/usr/bin/env python3
"""Generates shapes, spacing, type and motion from contracts/design-tokens/v1.

Reads shape.json, spacing.json, typography.json and motion.json, and writes five committed files
in AwradDesignSystem/Theme:
- AwradRadius.swift: the radius scale and the shape roles (`AwradCorner`, continuous corners).
- AwradStroke.swift: the line widths the design allows (`AwradStroke`).
- AwradSpacing.swift: the spacing scale and roles (`AwradSpacing`) and the standard sizes (`AwradSize`).
- AwradTextStyle.swift: the named text styles (`AwradTextStyle`), each on a bundled face of its family.
- AwradMotion.swift: easings, durations, springs (converted for SwiftUI), haptics, the named motions
  iOS uses (motions without "ios" in `platforms`, such as Android's `sheet`, aren't generated), and
  reduced motion.
- AwradElevation.swift: shape.json `elevation` as `AwradShadow`s for `.shadow(color:radius:x:y:)`.
  The contract's blur is the CSS/Figma blur, about twice SwiftUI's radius, so radius = blur / 2. The
  colour is a colour role; `shadow` is clear in dark, so dark mode has no shadow.

Spring conversion (contracts/design-tokens/v1/README.md): response = 2π / √stiffness and
dampingFraction = dampingRatio, with mass 1.

Nothing reads contracts/ at runtime. Run without arguments to rewrite the files. With --check
(scripts/validate), it fails when a committed file differs from what the contract generates. An
unknown key anywhere (a file's top-level group, a role, size, style, spring, haptic, stroke, elevation,
named motion or reduced motion) fails too, so a new token can't be silently dropped: teach the
generator its type first (`MOTION_KEYS` for motions, `KEYS` for the rest).
"""
import json
import math
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT.parent / "contracts" / "design-tokens" / "v1"
THEME = ROOT / "AwradKit" / "Sources" / "AwradDesignSystem" / "Theme"
HEADER = [
    "// Generated by scripts/generate-design-tokens.py from contracts/design-tokens/v1/{source}.",
    "// Don't edit: regenerate it. scripts/validate fails when it differs from the contract.",
    "",
]
NAME = re.compile(r"^[a-z][A-Za-z]*$")
TEXT_STYLES = {"largeTitle", "title", "title2", "title3", "headline", "subheadline", "body", "callout",
               "footnote", "caption", "caption2"}
# Each font family's bundled faces (`AwradFonts.Face`): the case prefix, then the weight's suffix.
FAMILIES = {"Google Sans Flex Rounded": "interface", "Noto Naskh Arabic": "naskh"}
WEIGHTS = {400: "Regular", 500: "Medium", 600: "SemiBold", 700: "Bold"}
STROKE_KEYS = {"width", "offset", "use"}
REDUCED_MOTION_KEYS = {"replaceWith", "duration", "easing", "use"}
COLORS = TOKENS / "colors.json"
# The keys each file, and each entry of its listed groups, may have. Anything else fails the generator.
KEYS = {
    "shape": {"version", "description", "corners", "scale", "roles", "strokes", "elevation"},
    "shape.roles": {"radius", "use"},
    "shape.elevation": {"y", "blur", "color", "use"},
    "spacing": {"version", "description", "scale", "roles", "sizes"},
    "spacing.roles": {"space", "use"},
    "spacing.sizes": {"value", "use"},
    "typography": {"version", "description", "fontFamily", "styles"},
    "typography.styles": {"size", "lineHeight", "weight", "iosTextStyle", "fontFamily", "tabularNumbers", "use"},
    "motion": {"version", "description", "easing", "duration", "spring", "haptic", "motions", "reducedMotion"},
    "motion.spring": {"dampingRatio", "stiffness", "use"},
    "motion.haptic": {"ios", "android", "use"},
}
HAPTIC = re.compile(r"sensoryFeedback\((\.[A-Za-z]+(?:\([a-z]+: \.[a-z]+\))?)\)")

# The Swift type of every key a named motion may use. `scale`/`opacity`/`points` are numbers as
# given; `ms` becomes seconds; the `*Ref` kinds name another token.
MOTION_KEYS = {
    "scaleFrom": "scale", "scaleTo": "scale", "cardScale": "scale", "buttonScale": "scale",
    "popScale": "scale", "iconScale": "scale", "pillScaleFrom": "scale",
    "fadeFrom": "opacity", "dim": "opacity",
    "offset": "points",
    "stagger": "ms", "maxStaggered": "count", "chevronRotation": "degrees",
    "duration": "durationRef", "pressDuration": "durationRef", "colorDuration": "durationRef",
    "fadeDuration": "durationRef", "fadeIn": "durationRef", "fadeOut": "durationRef",
    "easing": "easingRef", "pressEasing": "easingRef",
    "spring": "springRef", "pillSpring": "springRef", "iconSpring": "springRef", "releaseSpring": "springRef",
    "ringSpring": "springRef", "sizeSpring": "springRef", "fadeSpring": "springRef",
    "haptic": "hapticRef", "numberTransition": "text",
}


def check_keys(what: str, keys, allowed: str) -> None:
    unknown = set(keys) - KEYS[allowed]
    if unknown:
        raise SystemExit(f"design tokens: {what} has {sorted(unknown)}, which iOS doesn't generate yet")


def load(name: str) -> dict:
    tokens = json.loads((TOKENS / f"{name}.json").read_text(encoding="utf-8"))
    if tokens.get("version") != 1:
        raise SystemExit(f"design tokens: {name}.json isn't version 1")
    check_keys(f"{name}.json", tokens, name)
    for group in tokens:
        if f"{name}.{group}" in KEYS:
            for entry, spec in tokens[group].items():
                check_keys(f"{name}.json {group}.{entry}", spec, f"{name}.{group}")
    return tokens


def swift_name(key: str) -> str:
    """A scale key as a Swift name: a leading digit moves to the end (`2xl` is `xl2`)."""
    match = re.match(r"^(\d)([a-z]+)$", key)
    name = match.group(2) + match.group(1) if match else key
    if not re.match(r"^[a-z][A-Za-z0-9]*$", name):
        raise SystemExit(f"design tokens: {key!r} can't be a Swift name")
    return name


def type_name(key: str) -> str:
    return key[0].upper() + key[1:]


def number(value: float) -> str:
    """A number as Swift source: integers without a fraction, others shortest round-trip."""
    if float(value).is_integer():
        return str(int(value))
    return repr(round(float(value), 6))


def doc(text: str, indent: str) -> str:
    """A doc comment, wrapped to fit swift-format's 120 columns."""
    width = 120 - len(indent) - 4
    return "\n".join(f"{indent}/// {line}" for line in textwrap.wrap(" ".join(text.split()), width))


def table(name: str, value_type: str, entries: list[tuple[str, str]], indent: str = "    ") -> list[str]:
    """An internal `KeyValuePairs` of contract names to generated values, for the contract tests."""
    # swift-format drops the trailing comma of a one-element literal.
    comma = "," if len(entries) > 1 else ""
    return [
        f"{indent}static let {name}: KeyValuePairs<String, {value_type}> = [",
        *(f'{indent}    "{key}": {value}{comma}' for key, value in entries),
        f"{indent}]",
    ]


def radius_swift(shape: dict) -> str:
    scale, roles = shape["scale"], shape["roles"]
    if shape.get("corners") != "continuous":
        raise SystemExit("shape: iOS draws continuous corners; corners must be \"continuous\"")
    fixed = {key: value for key, value in scale.items() if value != "full"}
    lines = [
        *[line.format(source="shape.json") for line in HEADER],
        "import CoreGraphics",
        "",
        "/// Corner radii from the design tokens contract: a scale, and the role every shape uses.",
        "/// Screens use a role (`AwradRadius.card.shape`), never a number. Corners are continuous.",
        "nonisolated public enum AwradRadius {",
    ]
    for key, value in fixed.items():
        lines.append(f"    public static let {swift_name(key)}: CGFloat = {number(value)}")
    lines.append("")
    for role, spec in roles.items():
        if not NAME.match(role):
            raise SystemExit(f"shape: role {role!r} isn't lowerCamelCase")
        radius = spec["radius"]
        if radius not in scale:
            raise SystemExit(f"shape: role {role!r} uses {radius!r}, not on the scale")
        value = ".full" if scale[radius] == "full" else f".radius({swift_name(radius)})"
        lines += [doc(f"{spec['use']}: `{radius}`.", "    "), f"    public static let {role}: AwradCorner = {value}"]
    lines += [
        "",
        *table("scale", "CGFloat", [(key, swift_name(key)) for key in fixed]),
        *table("roles", "AwradCorner", [(role, role) for role in roles]),
        "}",
        "",
    ]
    return "\n".join(lines)


def stroke_swift(shape: dict) -> str:
    """The line widths of shape.json `strokes`; an `offset` becomes `<name>Offset`."""
    lines = [
        *[line.format(source="shape.json") for line in HEADER],
        "import CoreGraphics",
        "",
        "/// Line widths from the design tokens contract (shape.json `strokes`): every line the design allows,",
        "/// since shapes are otherwise filled, never outlined. Screens use a name, never a number.",
        "nonisolated public enum AwradStroke {",
    ]
    entries = []
    for name, spec in shape["strokes"].items():
        if not NAME.match(name):
            raise SystemExit(f"shape: stroke {name!r} isn't lowerCamelCase")
        unknown = set(spec) - STROKE_KEYS
        if unknown:
            raise SystemExit(f"shape: stroke {name!r} has {sorted(unknown)}, which iOS doesn't generate yet")
        lines += [doc(f"{spec['use']}.", "    "), f"    public static let {name}: CGFloat = {number(spec['width'])}"]
        entries.append((f"{name}.width", name))
        if "offset" in spec:
            lines += [
                f"    /// How far `{name}` sits outside what it outlines.",
                f"    public static let {name}Offset: CGFloat = {number(spec['offset'])}",
            ]
            entries.append((f"{name}.offset", f"{name}Offset"))
    lines += ["", *table("strokes", "CGFloat", entries), "}", ""]
    return "\n".join(lines)


def spacing_swift(spacing: dict) -> str:
    scale, roles, sizes = spacing["scale"], spacing["roles"], spacing["sizes"]
    lines = [
        *[line.format(source="spacing.json") for line in HEADER],
        "import CoreGraphics",
        "",
        "/// Spacing from the design tokens contract: a scale on a 4-point grid and named roles.",
        "/// Screens use a role or a scale name, never a number.",
        "nonisolated public enum AwradSpacing {",
    ]
    for key, value in scale.items():
        lines.append(f"    public static let {swift_name(key)}: CGFloat = {number(value)}")
    lines.append("")
    for role, spec in roles.items():
        if spec["space"] not in scale:
            raise SystemExit(f"spacing: role {role!r} uses {spec['space']!r}, not on the scale")
        lines += [
            doc(f"{spec['use']}: `{spec['space']}`.", "    "),
            f"    public static let {role}: CGFloat = {swift_name(spec['space'])}",
        ]
    lines += [
        "",
        *table("scale", "CGFloat", [(key, swift_name(key)) for key in scale]),
        *table("roles", "CGFloat", [(role, role) for role in roles]),
        "}",
        "",
        "/// Standard sizes from the design tokens contract (spacing.json `sizes`).",
        "nonisolated public enum AwradSize {",
    ]
    for size, spec in sizes.items():
        lines += [doc(f"{spec['use']}.", "    "), f"    public static let {size}: CGFloat = {number(spec['value'])}"]
    lines += ["", *table("sizes", "CGFloat", [(size, size) for size in sizes]), "}", ""]
    return "\n".join(lines)


def typography_swift(typography: dict) -> str:
    styles = typography["styles"]
    lines = [
        *[line.format(source="typography.json") for line in HEADER],
        "import SwiftUI",
        "",
        f"// Interface text is {typography['fontFamily']}; a style with its own fontFamily uses that family.",
        "// `AwradFonts.font(_:)` turns a style into a Font.",
        "extension AwradTextStyle {",
    ]
    for name, style in styles.items():
        if style["iosTextStyle"] not in TEXT_STYLES:
            raise SystemExit(f"typography: {name}.iosTextStyle {style['iosTextStyle']!r} isn't a Font.TextStyle")
        family = style.get("fontFamily", typography["fontFamily"])
        if family not in FAMILIES:
            raise SystemExit(f"typography: {name} uses {family!r}, which has no bundled faces")
        if style["weight"] not in WEIGHTS:
            raise SystemExit(f"typography: {name}.weight {style['weight']} has no bundled face")
        face = FAMILIES[family] + WEIGHTS[style["weight"]]
        tabular = "true" if style.get("tabularNumbers") else "false"
        own_family = f" {family}." if "fontFamily" in style else ""
        lines += [
            doc(f"{style['use']}. {number(style['size'])}/{number(style['lineHeight'])}, weight {style['weight']}."
                f"{own_family}", "    "),
            f"    public static let {name} = AwradTextStyle(",
            f'        name: "{name}", size: {number(style["size"])}, lineHeight: {number(style["lineHeight"])}, '
            f"weight: {style['weight']},",
            f"        face: .{face}, relativeTo: .{style['iosTextStyle']}, tabularNumbers: {tabular})",
        ]
    lines += ["", "    /// Every style, in contract order.", "    static let all: [AwradTextStyle] = ["]
    lines += [f"        {name}," for name in styles]
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def spring_conversion(spring: dict) -> tuple[float, float]:
    """(response, dampingFraction) for SwiftUI from (dampingRatio, stiffness) with mass 1."""
    return 2 * math.pi / math.sqrt(spring["stiffness"]), spring["dampingRatio"]


class Motion:
    def __init__(self, motion: dict):
        self.tokens = motion
        self.table: list[tuple[str, str]] = []  # contract path -> Swift Double expression
        self.names: list[tuple[str, str]] = []  # contract path -> Swift String expression

    def ref(self, kind: str, value: str, where: str) -> str:
        groups = {"durationRef": "duration", "easingRef": "easing", "springRef": "spring", "hapticRef": "haptic"}
        if value not in self.tokens[groups[kind]]:
            raise SystemExit(f"motion: {where} names {groups[kind]} {value!r}, which doesn't exist")
        if kind == "hapticRef":
            return f"AwradHaptic.{value}"
        return f"{type_name(groups[kind])}.{value}"

    def field(self, motion: str, path: list[str], value) -> list[str]:
        key = path[-1]
        kind = MOTION_KEYS.get(key)
        where = f"{motion}.{'.'.join(path)}"
        if kind is None:
            raise SystemExit(f"motion: {where} has no Swift type; add {key!r} to MOTION_KEYS")
        name = path[0] + "".join(type_name(part) for part in path[1:])
        owner = type_name(motion)
        literal = {
            "scale": ("CGFloat", lambda v: number(v)), "opacity": ("Double", lambda v: number(v)),
            "points": ("CGFloat", lambda v: number(v)), "ms": ("TimeInterval", lambda v: number(v / 1000)),
            "count": ("Int", lambda v: number(v)), "degrees": ("Angle", lambda v: f".degrees({number(v)})"),
            "text": ("String", lambda v: f'"{v}"'),
        }
        if kind in literal:
            swift_type, render = literal[kind]
            if kind == "text":
                self.names.append((where, f"{owner}.{name}"))
            elif kind == "degrees":
                self.table.append((where, f"{owner}.{name}.degrees"))
            else:
                self.table.append((where, f"Double({owner}.{name})"))
            return [f"        public static let {name}: {swift_type} = {render(value)}"]
        expression = self.ref(kind, value, where)
        if kind == "springRef":
            self.table += [(f"{where}.response", f"{owner}.{name}.response"),
                           (f"{where}.dampingFraction", f"{owner}.{name}.dampingFraction")]
        elif kind == "easingRef":
            self.table += [(f"{where}.{i}", f"{owner}.{name}.{c}") for i, c in enumerate(["x1", "y1", "x2", "y2"])]
        elif kind == "durationRef":
            self.table.append((where, f"{owner}.{name}"))
        else:
            self.names.append((where, f"{owner}.{name}.rawValue"))
        return [f"        public static let {name} = {expression}"]

    def swift(self) -> str:
        tokens = self.tokens
        lines = [
            *[line.format(source="motion.json") for line in HEADER],
            "import SwiftUI",
            "",
            "/// Motion from the design tokens contract. Durations are seconds; springs are converted for",
            "/// SwiftUI (response = 2π / √stiffness, dampingFraction = dampingRatio). Screens use the named",
            "/// motions and helpers (AwradMotion+Helpers.swift), never a raw animation.",
            "nonisolated public enum AwradMotion {",
            "    /// Cubic-bézier easings.",
            "    public enum Easing {",
        ]
        for name, points in tokens["easing"].items():
            lines.append(f"        public static let {name} = AwradCurve({', '.join(number(p) for p in points)})")
        lines += ["    }", "", "    /// Durations in seconds.", "    public enum Duration {"]
        for name, ms in tokens["duration"].items():
            lines.append(f"        public static let {name}: TimeInterval = {number(ms / 1000)}")
        lines += ["    }", "", "    /// Springs, converted from (dampingRatio, stiffness) with mass 1.", "    public enum Spring {"]
        for name, spring in tokens["spring"].items():
            response, damping = spring_conversion(spring)
            lines += [
                doc(f"{spring['use']}. dampingRatio {number(spring['dampingRatio'])}, stiffness "
                    f"{number(spring['stiffness'])}.", "        "),
                f"        public static let {name} = AwradSpring(response: {number(response)}, "
                f"dampingFraction: {number(damping)})",
            ]
        lines.append("    }")
        for motion, spec in tokens["motions"].items():
            if "ios" not in spec["platforms"]:
                continue
            lines += ["", doc(f"{spec['use']}.", "    "), f"    public enum {type_name(motion)} {{"]
            for key, value in spec.items():
                if key in ("platforms", "use"):
                    continue
                if isinstance(value, dict):
                    for inner, inner_value in value.items():
                        lines += self.field(motion, [key, inner], inner_value)
                else:
                    lines += self.field(motion, [key], value)
            lines.append("    }")
        reduced = tokens["reducedMotion"]
        if reduced["replaceWith"] != "crossfade":
            raise SystemExit("motion: iOS only knows the crossfade reduced motion")
        unknown = set(reduced) - REDUCED_MOTION_KEYS
        if unknown:
            raise SystemExit(f"motion: reducedMotion has {sorted(unknown)}, which iOS doesn't generate yet")
        lines += [
            "",
            doc(reduced["use"], "    "),
            "    public enum ReducedMotion {",
            f"        public static let duration = {self.ref('durationRef', reduced['duration'], 'reducedMotion')}",
            f"        public static let easing = {self.ref('easingRef', reduced['easing'], 'reducedMotion')}",
            "    }",
            "",
            "    /// The named motions iOS uses, by contract name.",
            "    static let motions: [String] = [",
            *(f'        "{m}",' for m, s in tokens["motions"].items() if "ios" in s["platforms"]),
            "    ]",
            *table("durations", "TimeInterval", [(n, f"Duration.{n}") for n in tokens["duration"]]),
            *table("easings", "AwradCurve", [(n, f"Easing.{n}") for n in tokens["easing"]]),
            *table("springs", "AwradSpring", [(n, f"Spring.{n}") for n in tokens["spring"]]),
            "    /// Every number of the named motions by contract path, references resolved (seconds, springs",
            "    /// converted, easings by control point).",
            *table("motionNumbers", "Double", self.table),
            "    /// Every haptic and text value of the named motions by contract path.",
            *table("motionNames", "String", self.names),
            "}",
            "",
            "/// Haptics: what each moment feels like. Haptics stay when motion is reduced.",
            "nonisolated public enum AwradHaptic: String, CaseIterable, Sendable {",
        ]
        for name in tokens["haptic"]:
            lines.append(f"    case {name}")
        lines += ["", "    /// The SwiftUI feedback, from the contract's iOS mapping.", "    public var feedback: SensoryFeedback {",
                  "        switch self {"]
        for name, haptic in tokens["haptic"].items():
            match = HAPTIC.search(haptic["ios"])
            if not match:
                raise SystemExit(f"motion: haptic {name!r} has no sensoryFeedback(…) for iOS")
            lines.append(f"        case .{name}: {match.group(1)}")
        lines += ["        }", "    }", "}", ""]
        return "\n".join(lines)


def elevation_swift(shape: dict) -> str:
    """shape.json `elevation` as `AwradShadow`s: radius = blur / 2, x 0, the colour a colour role."""
    roles = json.loads(COLORS.read_text(encoding="utf-8"))["roles"]
    lines = [
        *[line.format(source="shape.json") for line in HEADER],
        "import SwiftUI",
        "",
        "/// Shadows from the design tokens contract (shape.json `elevation`), applied with `awradElevation(_:)`.",
        "/// SwiftUI's shadow radius is about half the contract's (CSS/Figma) blur, so radius = blur / 2. The",
        "/// colour is a colour role that is clear in dark mode, so there is no shadow in dark.",
        "public enum AwradElevation {",
    ]
    numbers, colors = [], []
    for name, spec in shape["elevation"].items():
        if not NAME.match(name):
            raise SystemExit(f"shape: elevation {name!r} isn't lowerCamelCase")
        if spec["color"] not in roles:
            raise SystemExit(f"shape: elevation {name!r} uses {spec['color']!r}, which isn't a colour role")
        if spec["blur"] < 0:
            raise SystemExit(f"shape: elevation {name!r} has a negative blur")
        lines += [
            doc(f"{spec['use']}. y {number(spec['y'])}, blur {number(spec['blur'])}, `{spec['color']}`.", "    "),
            f"    public static let {name} = AwradShadow(color: AwradColors.{spec['color']}, "
            f"radius: {number(spec['blur'] / 2)}, x: 0, y: {number(spec['y'])})",
        ]
        numbers += [(f"{name}.y", f"Double({name}.y)"), (f"{name}.blur", f"Double({name}.radius * 2)")]
        colors.append((f"{name}.color", f'"{spec["color"]}"'))
    lines += [
        "",
        "    /// Every number by contract path (the blur back from the radius), for the contract tests.",
        *table("numbers", "Double", numbers),
        "    /// Every colour role by contract path.",
        *table("colors", "String", colors),
        "}",
        "",
    ]
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    shape = load("shape")
    return {
        THEME / "AwradRadius.swift": radius_swift(shape),
        THEME / "AwradStroke.swift": stroke_swift(shape),
        THEME / "AwradElevation.swift": elevation_swift(shape),
        THEME / "AwradSpacing.swift": spacing_swift(load("spacing")),
        THEME / "AwradTextStyle.swift": typography_swift(load("typography")),
        THEME / "AwradMotion.swift": Motion(load("motion")).swift(),
    }


def main() -> int:
    files = outputs()
    if sys.argv[1:] == ["--check"]:
        stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"design tokens: {path.relative_to(ROOT)} is stale or edited; run scripts/generate-design-tokens.py",
                  file=sys.stderr)
        if stale:
            return 1
        print("design tokens: shape, strokes, elevation, spacing, typography and motion match "
              "contracts/design-tokens/v1")
        return 0
    if sys.argv[1:]:
        print("usage: generate-design-tokens.py [--check]", file=sys.stderr)
        return 2
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print(f"design tokens: wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
