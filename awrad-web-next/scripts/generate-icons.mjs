// Generates src/shared/ui/icons.gen.tsx from the shared icon set (contracts/design-tokens/v1/
// icons.json and icons/*.svg, Material Symbols Rounded): one React component per icon name
// (`back` → BackIcon), filled with `currentColor` and `aria-hidden`, flipped in right-to-left
// layouts when the icon is `mirrorInRtl`. A key the generator doesn't know, an icon whose file
// is missing, or an SVG that isn't a plain path-only one on the 960 grid fails (token-keys.mjs).
// The output goes through the project's Prettier config, so it passes `format:check` as is.
//
//   node scripts/generate-icons.mjs           write the file (npm run icons)
//   node scripts/generate-icons.mjs --check   fail when the committed file is stale (npm run validate)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { checkKeys } from "./token-keys.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
export const SOURCE = join(HERE, "../../contracts/design-tokens/v1/icons.json");
export const ICON_DIR = join(HERE, "../../contracts/design-tokens/v1/icons");
export const TARGET = join(HERE, "../src/shared/ui/icons.gen.tsx");

/** Material Symbols' grid: every icon is drawn on it, so one viewBox serves them all. */
export const VIEW_BOX = "0 -960 960 960";

/** icons.json, and each named icon's SVG text by file name. */
export function readIcons() {
  const json = JSON.parse(readFileSync(SOURCE, "utf8"));
  const files = Object.fromEntries(
    Object.values(json.icons ?? {}).map(({ file }) => [file, readFileSync(join(ICON_DIR, file), "utf8")]),
  );
  return { json, files };
}

/** `forward` → `ForwardIcon`. */
export function componentName(name) {
  return `${name[0].toUpperCase()}${name.slice(1)}Icon`;
}

/** The path data of a plain path-only SVG on the 960 grid; throws on anything else. */
export function pathData(file, svg) {
  const tags = [...svg.matchAll(/<([a-zA-Z][\w:-]*)([^>]*)>/g)];
  const root = tags[0];
  if (root?.[1] !== "svg") throw new Error(`icons/${file}: not an SVG`);
  if (!root[2].includes(`viewBox="${VIEW_BOX}"`)) {
    throw new Error(`icons/${file}: viewBox must be "${VIEW_BOX}" (Material Symbols' grid)`);
  }
  const paths = tags.slice(1).map(([tag, element, attributes]) => {
    if (element !== "path") throw new Error(`icons/${file}: <${element}> isn't allowed; only <path>`);
    const match = /^\s+d="([^"]+)"\s*\/$/.exec(attributes);
    if (match === null) throw new Error(`icons/${file}: ${tag} must be <path d="…"/> with no other attributes`);
    return match[1];
  });
  if (paths.length === 0) throw new Error(`icons/${file}: no <path>`);
  return paths;
}

/** Every icon, checked: name, component, path data, mirroring and use, in icons.json's order. */
export function resolveIcons({ json, files }) {
  checkKeys("icons", json);
  return Object.entries(json.icons).map(([name, icon]) => {
    if (!/^[a-z][a-zA-Z0-9]*$/.test(name)) throw new Error(`icons.json ${name}: names are camelCase`);
    if (typeof icon.mirrorInRtl !== "boolean") throw new Error(`icons.json ${name}: mirrorInRtl must be true or false`);
    const svg = files[icon.file];
    if (svg === undefined) throw new Error(`icons.json ${name}: icons/${icon.file} is missing`);
    return {
      name,
      component: componentName(name),
      file: icon.file,
      paths: pathData(icon.file, svg),
      mirrorInRtl: icon.mirrorInRtl,
      use: (icon.use ?? "").replaceAll("*/", "* /"),
    };
  });
}

function componentLines(icon) {
  const mirrored = icon.mirrorInRtl ? " Mirrored in right-to-left layouts." : "";
  return [
    `/** \`${icon.name}\`: ${icon.use}. From ${icon.file}.${mirrored} */`,
    `export function ${icon.component}(props: IconProps): ReactElement {`,
    `  return <Svg {...props}${icon.mirrorInRtl ? " mirrorInRtl" : ""} paths={${JSON.stringify(icon.paths)}} />;`,
    "}",
    "",
  ];
}

/** The unformatted TSX for the icons. */
function renderSource(icons) {
  return [
    "// Generated by scripts/generate-icons.mjs from contracts/design-tokens/v1/icons.json and the",
    "// SVGs in its icons/ folder (Material Symbols Rounded, Apache 2.0, icons/LICENSE-MaterialSymbols.txt).",
    "// Don't edit: run `npm run icons`. `npm run validate` fails when this file is stale.",
    'import type { ReactElement } from "react";',
    'import { cx } from "./cx";',
    "",
    "/**",
    " * `icon` is the `icon` size (24, the default), `small` `iconSmall` (20). Icons are decorative",
    " * (`aria-hidden`): the control that holds one carries the label. The colour is the text colour.",
    " */",
    "export interface IconProps {",
    '  size?: "icon" | "small";',
    "}",
    "",
    "/** An icon component, for props such as `Button`'s `icon`. */",
    "export type Icon = (props: IconProps) => ReactElement;",
    "",
    "/** Every icon's shared name (icons.json). */",
    `export type IconName = ${icons.map((icon) => JSON.stringify(icon.name)).join(" | ")};`,
    "",
    "/**",
    ` * An icon's paths on Material Symbols' 960 grid (viewBox "${VIEW_BOX}"). Each component holds`,
    " * its own paths, so a build carries only the icons it uses.",
    " */",
    "function Svg({",
    "  paths,",
    '  size = "icon",',
    "  mirrorInRtl = false,",
    "}: IconProps & { paths: readonly string[]; mirrorInRtl?: boolean }): ReactElement {",
    "  return (",
    "    <svg",
    `      viewBox="${VIEW_BOX}"`,
    '      aria-hidden="true"',
    '      focusable="false"',
    '      fill="currentColor"',
    '      className={cx("shrink-0", size === "icon" ? "size-icon" : "size-icon-small", mirrorInRtl && "rtl:-scale-x-100")}',
    "    >",
    "      {paths.map((d) => (",
    "        <path key={d} d={d} />",
    "      ))}",
    "    </svg>",
    "  );",
    "}",
    "",
    ...icons.flatMap(componentLines),
    "/** Every icon by its shared name (the gallery; importing it brings in the whole set). */",
    "export const ICONS: Record<IconName, Icon> = {",
    ...icons.map((icon) => `  ${icon.name}: ${icon.component},`),
    "};",
    "",
  ].join("\n");
}

/** The formatted TSX for icons.json and its SVGs (`readIcons()`). */
export async function renderIconsTsx(source) {
  const options = (await resolveConfig(TARGET)) ?? {};
  return format(renderSource(resolveIcons(source)), { ...options, filepath: TARGET });
}

async function main() {
  const tsx = await renderIconsTsx(readIcons());
  if (process.argv.includes("--check")) {
    let committed = "";
    try {
      committed = readFileSync(TARGET, "utf8");
    } catch {
      // A missing file is stale too.
    }
    if (committed !== tsx) {
      console.error("src/shared/ui/icons.gen.tsx is stale or edited by hand. Run: npm run icons");
      process.exit(1);
    }
    console.log("icons: up to date with contracts/design-tokens/v1/icons.json");
    return;
  }
  writeFileSync(TARGET, tsx);
  console.log("wrote src/shared/ui/icons.gen.tsx");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
