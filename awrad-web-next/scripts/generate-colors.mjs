// Generates src/shared/ui/colors.gen.css from the shared colour tokens
// (contracts/design-tokens/v1/colors.json): one custom property per role, light in
// :root and dark under prefers-color-scheme, plus the Tailwind theme that names them
// (bg-surface, text-on-surface, border-outline-strong, …) and nothing else. The `states`
// (disabled) are opacities, not colours: an --awrad-state-* property and an opacity-* class each.
//
//   node scripts/generate-colors.mjs           write the file (npm run tokens:colors)
//   node scripts/generate-colors.mjs --check   fail when the committed file is stale (npm run validate)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const SOURCE = join(HERE, "../../contracts/design-tokens/v1/colors.json");
export const TARGET = join(HERE, "../src/shared/ui/colors.gen.css");
const HEX = /^#[0-9A-Fa-f]{6}(?:[0-9A-Fa-f]{2})?$/;
const SCHEMES = ["light", "dark"];

/** `onSurfaceVariant` → `on-surface-variant`, the name Tailwind classes use. */
export function kebab(role) {
  return role.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

/** The CSS for a parsed colors.json. Values are copied as written, so `#RRGGBBAA` keeps its alpha. */
export function renderColorsCss(tokens) {
  const roles = Object.entries(tokens.roles);
  if (roles.length === 0) throw new Error("colors.json has no roles");
  for (const [role, value] of roles) {
    for (const scheme of SCHEMES) {
      if (typeof value[scheme] !== "string" || !HEX.test(value[scheme])) {
        throw new Error(`colors.json: ${role}.${scheme} must be #RRGGBB or #RRGGBBAA, got ${String(value[scheme])}`);
      }
    }
  }
  const declarations = (scheme, indent) =>
    roles.map(([role, value]) => `${indent}--awrad-color-${kebab(role)}: ${value[scheme]};`).join("\n");
  const states = renderStates(tokens.states ?? {});
  return [
    "/*",
    " * Generated by scripts/generate-colors.mjs from contracts/design-tokens/v1/colors.json.",
    " * Don't edit: run `npm run tokens:colors`. `npm run validate` fails when this file is stale.",
    " */",
    "",
    "/* The colour roles: light by default, dark when the system asks for it. */",
    ":root {",
    declarations("light", "  "),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    "  :root {",
    declarations("dark", "    "),
    "  }",
    "}",
    "",
    "/* Tailwind: these roles are the only colours (Tailwind's default palette is removed). */",
    "@theme inline {",
    "  --color-*: initial;",
    roles.map(([role]) => `  --color-${kebab(role)}: var(--awrad-color-${kebab(role)});`).join("\n"),
    "}",
    "",
    ...states,
  ].join("\n");
}

/**
 * colors.json `states`: a state is drawn at an opacity, not in colours of its own (a disabled
 * control keeps its colours at 38%). One `--awrad-state-<state>-opacity` and an
 * `opacity-<state>` class each (disabled:opacity-disabled).
 */
function renderStates(states) {
  const entries = Object.entries(states);
  if (entries.length === 0) return [];
  for (const [state, value] of entries) {
    const opacity = value.opacity;
    if (typeof opacity !== "number" || !(opacity > 0 && opacity < 1)) {
      throw new Error(`colors.json: states.${state}.opacity must be a number between 0 and 1, got ${String(opacity)}`);
    }
  }
  return [
    "/* States (colors.json `states`): drawn at an opacity, with no colours of their own. */",
    ":root {",
    ...entries.map(([state, value]) => `  --awrad-state-${kebab(state)}-opacity: ${String(value.opacity)};`),
    "}",
    ...entries.flatMap(([state]) => [
      `@utility opacity-${kebab(state)} {`,
      `  opacity: var(--awrad-state-${kebab(state)}-opacity);`,
      "}",
    ]),
    "",
  ];
}

function main() {
  const css = renderColorsCss(JSON.parse(readFileSync(SOURCE, "utf8")));
  if (process.argv.includes("--check")) {
    let committed = "";
    try {
      committed = readFileSync(TARGET, "utf8");
    } catch {
      // A missing file is stale too.
    }
    if (committed !== css) {
      console.error("src/shared/ui/colors.gen.css is stale or edited by hand. Run: npm run tokens:colors");
      process.exit(1);
    }
    console.log("colours: up to date with contracts/design-tokens/v1/colors.json");
    return;
  }
  writeFileSync(TARGET, css);
  console.log("wrote src/shared/ui/colors.gen.css");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
