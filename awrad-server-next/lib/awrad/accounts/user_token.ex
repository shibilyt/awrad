defmodule Awrad.Accounts.UserToken do
  @moduledoc """
  A browser session token, as generated by `phx.gen.auth` (ADR-2026-10-15).

  Deliberate changes:
    * the magic-link and change-email tokens are removed (root ADR-2026-10-26:
      no links; emailed codes live in `Awrad.Accounts.EmailCode`), so this
      table only holds `"session"` tokens;
    * each token is a browser session in the account's session list (slice
      2b): it has a `name` summarising the browser ("Firefox on Windows",
      `nil` when unknown) and `last_seen_at`;
    * a reissue replaces the token in place (same row, same session) and keeps
      the replaced one as `previous_token`, accepted until
      `previous_token_valid_until`, so requests already in flight with the old
      cookie still work (`Awrad.Accounts.BrowserSessions`).

  Tokens are stored as they are: the session cookie that carries them is
  signed, and the database row is what lets one session end on its own.
  """

  use Ecto.Schema

  @rand_size 32
  @session_validity_in_days 14

  @type t :: %__MODULE__{
          id: Ecto.UUID.t() | nil,
          user_id: Ecto.UUID.t() | nil,
          token: binary() | nil,
          context: String.t() | nil,
          name: String.t() | nil,
          last_seen_at: DateTime.t() | nil,
          previous_token: binary() | nil,
          previous_token_valid_until: DateTime.t() | nil,
          authenticated_at: DateTime.t() | nil,
          inserted_at: DateTime.t() | nil
        }

  @primary_key {:id, :binary_id, autogenerate: true}
  @foreign_key_type :binary_id
  schema "users_tokens" do
    field :token, :binary, redact: true
    field :context, :string
    field :sent_to, :string
    field :name, :string
    field :last_seen_at, :utc_datetime
    field :previous_token, :binary, redact: true
    field :previous_token_valid_until, :utc_datetime
    field :authenticated_at, :utc_datetime
    belongs_to :user, Awrad.Accounts.User

    timestamps(type: :utc_datetime, updated_at: false)
  end

  @doc "Days a session token stays valid after it was issued (or last reissued)."
  @spec validity_in_days() :: 14
  def validity_in_days, do: @session_validity_in_days

  @doc "A new random token value."
  @spec generate() :: binary()
  def generate, do: :crypto.strong_rand_bytes(@rand_size)

  @doc """
  Builds a session token for `user` signing in from a browser called `name`.
  Returns the token and the row to insert.
  """
  @spec build_session_token(Awrad.Accounts.User.t(), String.t() | nil) :: {binary(), t()}
  def build_session_token(user, name) do
    token = generate()
    now = DateTime.utc_now(:second)

    {token,
     %__MODULE__{
       token: token,
       context: "session",
       user_id: user.id,
       name: name,
       last_seen_at: now,
       authenticated_at: user.authenticated_at || now
     }}
  end
end
