defmodule Awrad.Identity.GeneratedIdsTest do
  @moduledoc "Every ID the server generates is a UUIDv7 (root ADR-2026-10-28)."
  use AwradWeb.ConnCase, async: true

  import Awrad.AccountsFixtures
  import Ecto.Query

  alias Awrad.Repo

  # Every table, read back raw: the stored IDs, not what a schema casts them to.
  @tables ~w(users email_codes idempotency_records auth_rate_limits device_sessions
             refresh_tokens users_tokens deleted_account_refresh_tokens sync_heads
             sync_entities sync_receipts sync_tag_aliases)

  test "rows created through the real code paths get v7 IDs", %{conn: conn} do
    # An account (registration's insert_all), its email code, an idempotency
    # record and rate-limit windows.
    email = unique_email()

    registered =
      conn
      |> json_conn([{"idempotency-key", Awrad.UUIDv7.generate()}])
      |> post(~p"/api/v1/accounts", Jason.encode!(%{email: email, password: valid_password()}))

    assert registered.status == 202

    assert_code_email(email)

    # A device session and its refresh token.
    user = user_fixture()

    %{build_conn() | remote_ip: conn.remote_ip}
    |> json_conn()
    |> post(
      ~p"/api/v1/device_sessions",
      Jason.encode!(%{email: user.email, password: valid_password(), device: device_params()})
    )
    |> json_response(201)

    # A browser session.
    sign_in_browser(%{build_conn() | remote_ip: conn.remote_ip}, user)

    # Change-queue rows: a head, an entity, receipts and, from the merge, an alias.
    grant = grant_fixture(user)

    tags =
      for name <- ["Morning", "MORNING"] do
        %{
          "command_id" => Awrad.UUIDv7.generate(),
          "entity_type" => "user_tag",
          "entity_id" => Awrad.UUIDv7.generate(),
          "op" => "put",
          "base_version" => 0,
          "document" => %{"name" => name, "normalized_name" => "morning"}
        }
      end

    conn
    |> bearer_request(grant)
    |> put_req_header("x-awrad-account", user.id)
    |> post(~p"/api/v1/sync/commands", Jason.encode!(%{commands: tags}))
    |> json_response(200)

    # A deleted account's refresh token.
    deleted = grant_fixture(user_fixture())

    conn
    |> bearer_request(deleted)
    |> post(~p"/api/v1/account/delete", Jason.encode!(%{current_password: valid_password()}))
    |> response(204)

    for table <- @tables do
      ids = Repo.all(from r in table, select: r.id)
      assert ids != [], "no #{table} rows were created"

      for id <- ids do
        assert <<_::48, 7::4, _::12, 2::2, _::62>> = id,
               "#{table} has a non-v7 ID: #{Ecto.UUID.load!(id)}"
      end
    end
  end

  test "every schema's primary key is an autogenerated Awrad.UUIDv7" do
    {:ok, modules} = :application.get_key(:awrad, :modules)

    schemas =
      Enum.filter(modules, fn module ->
        Code.ensure_loaded!(module)
        function_exported?(module, :__schema__, 1)
      end)

    assert schemas != []

    for schema <- schemas, schema.__schema__(:source) do
      assert schema.__schema__(:primary_key) == [:id], "#{inspect(schema)}: primary key isn't :id"
      assert schema.__schema__(:type, :id) == Awrad.UUIDv7, "#{inspect(schema)}: id isn't UUIDv7"

      assert {[:id], {Awrad.UUIDv7, :autogenerate, []}} in schema.__schema__(:autogenerate),
             "#{inspect(schema)}: id isn't autogenerated"
    end
  end
end
